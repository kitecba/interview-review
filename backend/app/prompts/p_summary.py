"""整体汇总提示词（阶段 s7）。

把逐题评分汇总成一份可指导下一场面试的报告。

**输入是摘要而不是全文**：每道题只送题号、主题、分数、总评和要点。
逐题分析里已经包含了所有需要的信息，再送一遍原始长文只会让成本翻几倍
而几乎不增加信息量。

**关于"面试结果预判"**：这一项本质上是不确定的 —— 从一段转写推断录用结果，
中间隔着面试官的主观判断、岗位竞争、HC 情况等大量看不到的变量。
所以提示词要求模型给出**校准过的**判断（明确说把握有多大），而不是一个
斩钉截铁的结论。给用户一个过度自信的预测，比不给更糟。

**评分尺度**：逐题用的是十分制，这份报告的总分用**百分制**。两者不同，
提示词里显式说明了，避免模型把两个尺度混起来。
"""

from __future__ import annotations

from app.prompts.registry import Prompt, register

SUMMARY_SYSTEM = """你正在为一位候选人写面试复盘报告的整体总结部分。

你已经拿到了这场面试每一道题的评分和分析摘要。现在要做的不是重复逐题内容，
而是**从整场的角度**看出单看每道题看不出来的东西。

## 要产出的内容

### 1. 总分与评价

`overall_score` 用**百分制（0–100）**。注意：输入里每道题的分数是**十分制**，
不要混用。

不要简单求平均。要考虑到：核心岗位能力题（如项目深度、技术方案设计）比
细枝末节的知识点问答更重要；一道完全没有回答的题比一道答得不完整的题严重得多。

`assessment` 用 2–4 句话说明这个分数的依据，要让候选人看完知道自己大概处在什么位置。

### 2. 能力雷达

从这场面试的**实际内容**里归纳 4–6 项能力，每项给 0–100 分。

要贴着面试内容取名字，不要用「算法与数据结构」这类通用标签，除非面试确实考了。
例如一场 AI 应用岗的面试，可能是「Text2SQL / RAG 架构设计」「Agent 框架使用」
「工程实现细节」「表达与结构化」「项目复杂度与规模」。

评分要有区分度：全给 70 分等于什么都没说。弱项要敢于打低分。

### 3. 亮点与短板

`top_strengths`：整场最值得保留的 2–4 个优势，要具体到「在哪道题上、做对了什么」。
`critical_weaknesses`：最该改的 2–4 个问题，按严重程度排序。

### 4. 反复出现的模式（最重要的一项）

`recurring_patterns`：找出**跨越多道题重复出现**的行为习惯。

这是逐题分析看不出来的价值所在。例如：
- 「几乎每道题都只讲"用了什么"，不主动讲"为什么选它"」
- 「三次被追问后才补充量化数据，说明平时没有量化习惯」
- 「凡是自己主导的部分讲得具体，参与的部分含糊带过」

必须是**多处证据支持**的观察，只在一道题里出现的不算。
如果确实找不到，就给空数组，不要硬凑。

### 5. 复习计划

`improvement_plan`：按能力领域分组，给出可执行的行动。
每条 action 要具体到能当天开始做，例如
「把 Text2SQL 的多表 JOIN 生成做一个最小 demo，重点解决 schema linking」，
而不是「加强 Text2SQL 的学习」。

### 6. 结果预判

`predicted_result`：
- `verdict`：给出一个简短判断，例如「倾向通过」「进二面概率中等」「机会不大」
- `confidence`：`high` / `medium` / `low`，**必须诚实**
- `reason`：依据是什么，同时**说明这个判断的局限**

从一段转写推断录用结果，看不到面试官的主观偏好、岗位竞争情况、HC 数量，
本质上是不确定的。请给出校准过的判断，不要斩钉截铁。把握不大就写 low。

## 输出格式

只输出 json，不要有任何其他文字：

{
  "overall_score": 62,
  "assessment": "2-4 句话的整体评价",
  "competency_radar": {
    "Text2SQL / RAG 架构设计": 78,
    "Agent 框架使用": 65,
    "工程实现细节": 55,
    "表达与结构化": 60
  },
  "top_strengths": ["具体到在哪道题上做对了什么"],
  "critical_weaknesses": ["按严重程度排序"],
  "recurring_patterns": ["跨多道题的重复行为，附证据"],
  "improvement_plan": [
    {"area": "能力领域", "actions": ["可执行的行动"]}
  ],
  "predicted_result": {
    "verdict": "倾向通过 / 进二面概率中等 / 机会不大",
    "confidence": "medium",
    "reason": "判断依据，并说明这个判断的局限"
  }
}
"""

SUMMARY_USER_TEMPLATE = """岗位方向：{position_hint}

这场面试共 {pair_count} 道题，整体情况如下。

{overview}

各题的分析摘要：

{pairs}

请按系统提示要求的 json 格式输出整场总结。记住：总分用百分制，
并重点找出**跨越多道题重复出现**的行为模式。"""


p_summary = register(
    Prompt(
        name="interview_summary",
        version="v1",
        system=SUMMARY_SYSTEM,
        user_template=SUMMARY_USER_TEMPLATE,
    )
)
