"""转写纠错提示词（阶段 s3）。

**要解决的问题**：ASR 对中英混合的技术名词识别很差。实测（真实面试录音）：

    SQL          → circle          （同一场面试里反复出现）
    Text2SQL     → test to circle
    LangGraph    → long graph / long group
    RAG          → R G
    Agent        → A
    checkpointer → take point ter
    渐进式披露    → 鉴接数披露
    精排          → 金牌
    向量          → 相量 / 香量

这些错误里有一部分读者能靠上下文自行纠正（`long graph` 显然是 LangGraph），
但有一类很危险 —— 错出来的词在中文里读得通、语义却完全错了。
合成音频测试里出现过 `key → 接着`（「重点看 key 这列」变成「重点看接着两列」），
这种句子读起来毫无破绽，下游的大模型很可能察觉不到。

**设计上的取舍**：让模型输出**改动清单**而不是直接返回改写后的全文。两个原因：

1. **可核对。** 用户能在界面上逐条看到「把什么改成了什么、为什么」，
   而不是面对一份不知改了哪里的文本。
2. **降低过度修改的危害。** 大模型有润色冲动，如果让它直接返回全文，
   它可能顺手把口语化的表达"修"得更书面，那就不是在纠错而是在篡改了。
   只允许它以「原文 → 修正」的形式提改动，越界会很明显。

提示词里反复强调「拿不准就不要改」，因为漏改的代价（保持原样）远小于错改的代价
（引入一个原本不存在的事实）。
"""

from __future__ import annotations

from app.prompts.registry import Prompt, register

REPAIR_SYSTEM = """你是一名中文技术面试录音的转写校对员。

你的唯一任务是：找出语音识别（ASR）造成的**识别错误**并修正。

## 只修这些

1. **中英混合的技术名词被识别错**，例如：
   - SQL 被识别成"circle"、"circle"、"sequel"
   - LangGraph 被识别成"long graph"、"long group"
   - RAG 被识别成"R G"、"rag"
   - Agent 被识别成"A"、"阿根特"
   - 向量 被识别成"相量"、"香量"
   - 精排 被识别成"金牌"
   - 渐进式披露 被识别成"鉴接数披露"、"建立式披露"
2. **同音字、近音字错误**：例如"去虫"应为"去重"、"电用模型"应为"调用模型"。
3. **英文词被误听成中文**：例如"key"被识别成"接着"、"case"被识别成"开始"。

## 绝对不要做的事

- 不要改写句子结构，不要润色措辞，不要把口语改书面语。
- 不要补充原文没有的内容。哪怕你觉得这里"应该"提到某个知识点，也不要加。
- 不要修正说话人的语法或用词习惯 —— 那是他的表达，不是识别错误。
- 不要改动专业观点、数字、人名、公司名，除非它们明显是识别错误。
- **拿不准就不要改。** 漏改的代价是保持原样，错改的代价是凭空编造出一个事实。
  后者的危害大得多。

## 判断依据

这是一场中文技术面试（AI 应用 / 后端方向），说话人会用中英文混说的方式
聊技术。遇到"读起来通顺、但在这个语境下讲不通"的词，优先怀疑是识别错误。

## 输出格式

只输出 json，不要有任何其他文字。结构如下：

{
  "corrections": [
    {
      "seq": 12,
      "original": "让A能够去直接写到circle中",
      "corrected": "让 AI 能够去直接写到 SQL 中",
      "reason": "A 应为 Agent/AI，circle 应为 SQL"
    }
  ]
}

规则：
- `seq` 是句子序号，必须来自输入。
- `original` 必须是该句**原样**的文本片段（可以只截取有问题的那一小段）。
- `corrected` 是修正后的对应片段。
- 只列出**确实有改动**的句子。没有改动的句子不要出现在结果里。
- 如果整批都没有需要改的，返回 {"corrections": []}。
"""

REPAIR_USER_TEMPLATE = """以下是面试录音转写的第 {batch_no} 批（共 {batch_total} 批）。

每行格式：`序号 [说话人] 文本`（时间为 mm:ss）

{context_block}待校对的句子：

{segments}

请找出其中的识别错误，按系统提示要求的 json 格式输出。"""


p_repair = register(
    Prompt(
        name="repair",
        # 改提示词内容时务必同步升值，否则旧结果会被幂等机制错误复用
        version="v1",
        system=REPAIR_SYSTEM,
        user_template=REPAIR_USER_TEMPLATE,
    )
)
