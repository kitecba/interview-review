"""问答切分提示词（阶段 s5）。

**要解决的问题**：把一场面试的转写切成「问题-回答」对，供后续逐题评分。

**两个来自实测的约束**：

1. **说话人标签不可靠。** 真实录音里 40% 的"发言回合"只有一句话，同一段中
   同一个标签既在提问又在回答。所以切分必须靠内容（疑问句、话轮转换、话题变化），
   标签只能当弱旁证。上游 s4 已经把这场录音标为 `label_reliability=low`。

2. **同一句里可能混了两个角色。** ASR 靠停顿断句，面试官问完、候选人紧接着答
   而中间停顿很短时，两段话会被并进同一句。所以不能假设"一句 = 一个人的一次发言"。

**核心设计：让模型只输出序号，不重抄文本。**

输出里只包含每个问答对由哪些序号组成，问题文本和回答文本由程序按序号还原。
这样做有三个好处：

- **输出极小**，不会有截断风险（s3 就是因为输出过大被截断过）
- **模型没有机会改写原文** —— 它无法在复述时悄悄润色，只能做归属判断
- **成本低**，且引用关系精确到句，便于前端点击跳回原文

代价是模型得准确追踪序号，这靠每行都带序号来保证。
"""

from __future__ import annotations

from app.prompts.registry import Prompt, register

SEGMENT_SYSTEM = """你在把一场中文技术面试的录音转写切分成「问题-回答」对。

## 输入格式

每行格式：`序号 [说话人N] [mm:ss] 文本`

## 重要前提：说话人标签不可靠

`[说话人N]` 标签来自声纹聚类，在长录音里会频繁出错：同一句话的两半可能被标成
不同说话人，同一个标签可能既在提问又在回答。**请以内容为主要判断依据**，
标签只能当作很弱的旁证。

### 最容易犯的错误，请特别警惕

**面试官的一句话被从中间切开、两半标成了不同说话人。**

真实例子（这就是模型的原始输出，不是假设）：

```
10 [说话人0] [00:10] 那最近的一个是。
11 [说话人1] [00:12] 这个仓储系统吗？
```

这两行**都是面试官说的**，合起来是一句完整的问题：「那最近的一个是这个仓储系统吗？」
如果因为标签从说话人0 变成了说话人1，就把第一行当作"问题"、第二行当作"回答"，
那么"回答"栏里装的就是面试官的问句 —— 后续给候选人打分时会拿这句话去评他，
这是**实质性错判**，不是小噪声。

所以：**判断某一行属于问题还是回答，看的是它在内容上是不是一个提问/一个应答，
而不是它与上一行的标签是否相同。** 相邻两行标签不同，完全可能属于同一个人；
标签相同，也完全可能是两个人在对话。

两种情况都要能处理：
- 面试官的问句横跨两行 → 两行都算**问题**
- 候选人的回答被切成两行 → 两行都算**回答**

## 切分单位

**以面试官提出的一个问题为单位**。一个问题和候选人针对它的回答，构成一个问答对。

处理这几种情况：

1. **追问**：面试官在候选人回答后，就同一主题继续追问。这是一个**独立的**问答对，
   `is_followup` 设为 true，`parent_seq` 指向被追问的那个问答对的 `seq`。
2. **面试官连续发问**：如果面试官一口气抛出几个相关的问题、候选人一起回答了，
   合并成一个问答对，`topic` 概括它们的共同点。
3. **与考察无关的对话**：寒暄、调试设备、约时间、聊天气。`is_off_topic` 设为 true，
   但**仍然要输出**，以保证覆盖完整。
4. **候选人被打断、或面试官自问自答**：按实际内容归属，不要硬凑。

## 输出格式：只给序号，不要重抄文本

**这是硬性要求。** 你只需要给出每个问答对由哪些序号组成，程序会据此还原文本。
重抄一遍文本没有意义，只会在复述时引入偏差。

只输出 json：

{
  "qa_pairs": [
    {
      "seq": 1,
      "topic": "Text2SQL 方案选型",
      "question_seqs": [1, 2],
      "answer_seqs": [3, 4, 5, 6],
      "is_followup": false,
      "parent_seq": null,
      "is_off_topic": false,
      "boundary": []
    }
  ]
}

字段说明：
- `seq`：问答对的顺序号，从 1 开始。
- `topic`：不超过 15 字的短语，例如「Text2SQL 方案选型」「LangGraph 使用经验」
  「自我介绍」「反问环节」。不要写成完整句子。
- `question_seqs` / `answer_seqs`：组成该问答对的句子序号数组。
- `parent_seq`：仅当 `is_followup` 为 true 时填写，指向被追问的问答对的 `seq`。
- `boundary`：**仅当一个句子横跨问答边界时才用**，见下节。不需要时给空数组。

## boundary：处理"一句里混了两个角色"

有时一个句子前半截是面试官的话、后半截是候选人的话（或反过来）；
也可能面试官的问题被切开，后半截落在了下一句里。这种情况整句归属必然有一半是错的。

这时用 `boundary` 指明切分位置：

{"seq": 6, "question_prefix": "这个仓储系统吗？"}

含义是：**第 6 句开头的「这个仓储系统吗？」属于问题，这一句剩下的部分属于回答。**

- `question_prefix` 必须与该句开头的文字**逐字一致**（包括标点）。
  对不上时这一项会被程序直接忽略 —— 这是防止你改写到原文的手段。
- 一句只需要一项；不需要切分的句子不要出现在这里。
- 只有在整句归属明显不对时才用它。多数句子不需要。

例子：面试官问「那最近的一个是这个仓储系统吗？」，ASR 把它切成两行并标成了
不同说话人。如果这两行分属"问题"和"回答"两侧，就要用 boundary 把后半截拉回问题。


## 必须遵守的约束

- 序号必须来自输入，不得编造。
- **同一个序号不能出现在两个问答对里。**
- 所有问答对的序号合起来，应当覆盖输入的绝大部分行。
- 按时间顺序排列问答对。
"""

SEGMENT_USER_TEMPLATE = """这是一场面试的转写文本。

背景：
- 岗位方向：{position_hint}
- 已判定：{role_hint}
- 标签可信度：{label_reliability}
- 共 {segment_count} 句，时长约 {duration_minutes:.0f} 分钟

转写文本：

{transcript}

请按系统提示要求的 json 格式输出切分结果。记住：只输出序号，不要重抄文本。"""


p_segment = register(
    Prompt(
        name="qa_segmentation",
        # v2：加强对「面试官问句被跨标签切开」这一具体错误的说明。
        #     v1 实测有 3/17 个问答对把面试官的问句当成了候选人的回答。
        # v3：新增 boundary 字段，允许模型对横跨边界的句子指定切分位置。
        #     v2 修掉了大部分，但仍有 3/18 对因「一句里混了两个角色」而归属错误 ——
        #     整句归属在这种结构上做不到正确。
        version="v3",
        system=SEGMENT_SYSTEM,
        user_template=SEGMENT_USER_TEMPLATE,
    )
)
