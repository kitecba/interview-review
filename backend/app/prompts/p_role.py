"""角色判定提示词（阶段 s4）。

**要解决的问题**：ASR 只返回匿名的 `speaker_id`（0/1/2…），不告诉你谁是面试官。
而且这个编号**不跨录音稳定**，同一场录音里也会漂。

**为什么不能"按 speaker_id 分组投票"**：真实面试录音实测，125 句被切成 52 个
"发言回合"，其中 40% 的回合只有一句话。真实面试应该是"面试官问一句、候选人
讲一大段"，长回合占多数。单句回合占到四成，说明标签在句级别频繁跳变。

实测捕捉到的具体错误：面试官的一句话被从中间切开、两半分属不同标签，
紧接着候选人的回答又和面试官的提问同属一个标签 —— 同一段里 S0 既在问又在答。

所以提示词的第一件事是**明确告诉模型标签不可信**，要求它以内容为主要依据，
把标签降级成很弱的旁证。这也是本阶段输出的核心价值：模型给的是"整体上谁在
扮演什么角色"，而不是逐句的标签复核。

另外要求模型额外报告 `label_reliability`（标签可信度）—— 这个字段会直接影响
下游 s5 问答切分的策略，也会在界面上提示用户是否需要手工改判。
"""

from __future__ import annotations

from app.prompts.registry import Prompt, register

ROLE_SYSTEM = """你正在分析一段中文技术面试录音的转写文本，任务是判断每个说话人的角色。

## 输入格式

每行格式：`序号 [说话人N] [mm:ss] 文本`

## 极其重要的前提：说话人标签不可靠

这些 `[说话人N]` 标签来自语音识别的声纹聚类，**在长录音里会频繁出错**：

- 同一句话的两半可能被标成不同说话人
- 同一个标签可能既在提问又在回答
- 实测中约四成的"发言回合"只有一句话，远高于真实面试的比例

因此：

- **以内容为主要判断依据**，标签只能当作很弱的旁证。
- 不要因为某句标着 `[说话人0]` 就认定它是面试官说的。
- 你要判断的是「这个编号整体上在扮演什么角色」，而不是逐句复核标签对不对。

## 判断依据

**面试官**的特征：
- 提问、追问、要求展开：「你能说一下…」「那你觉得…」「具体是怎么做的」「为什么」
- 引导流程：「请先做个自我介绍」「你有什么想问我的吗」「今天先到这里」
- 话语普遍较短，疑问句比例高

**候选人**的特征：
- 讲述自己的经历、项目、技术方案、遇到的问题和解决方式
- 回答、解释、举例、给出理由
- 话语普遍较长，陈述句比例高，常出现"我负责""我们当时""我的做法是"

## 需要额外判断的两件事

1. **是否群面**（多个候选人）。如果出现两个以上都在讲自己经历的人，`is_multi_candidate` 设为 true。
2. **标签可信度** `label_reliability`：
   - `high`：标签基本能对上角色，切换有规律
   - `medium`：有少量明显错位，但整体可用
   - `low`：标签频繁跳变，同一标签既提问又回答，明显不可依赖

## 输出格式

只输出 json，不要有任何其他文字：

{
  "speakers": [
    {"speaker_raw_id": 0, "role": "interviewer", "confidence": 0.85,
     "evidence": "反复出现『你能说一下』『具体怎么做的』，句子短，疑问句为主"},
    {"speaker_raw_id": 1, "role": "candidate", "confidence": 0.9,
     "evidence": "大段讲述自己的项目经历和技术方案，『我负责』『我们的做法是』"}
  ],
  "is_multi_candidate": false,
  "label_reliability": "low",
  "label_issues": "多处出现同一标签既提问又回答，例如第 498–510 秒附近",
  "needs_manual_review": true,
  "notes": "标签抖动明显，但整体上说话人0偏向面试官"
}

字段说明：
- `role` 取值只能是 `interviewer` / `candidate` / `unknown`
- `confidence` 是 0–1 的小数
- `evidence` 要引用文本里的**具体措辞**，不要写"根据上下文判断"这种空话
- `needs_manual_review`：当置信度低于 0.6、或标签可信度为 low、或存在多人难以区分时，设为 true
"""

ROLE_USER_TEMPLATE = """这是一场面试的转写文本。

背景信息：
- 岗位方向：{position_hint}
- 总时长约 {duration_minutes:.0f} 分钟，共 {segment_count} 句
- 出现的说话人编号：{speaker_ids}

转写文本：

{transcript}

请按系统提示要求的 json 格式输出你的判断。"""


p_role = register(
    Prompt(
        name="role_mapping",
        version="v1",
        system=ROLE_SYSTEM,
        user_template=ROLE_USER_TEMPLATE,
    )
)
